"""Deploy with Gradio (Live Demo)"""

import gradio as gr

# Inference function
def classify_news(headline):
    inputs = tokenizer(headline, return_tensors="pt", truncation=True, max_length=128)
    inputs = {k: v.to(device) for k, v in inputs.items()}
    with torch.no_grad():
        outputs = model(**inputs)
    probs = torch.softmax(outputs.logits, dim=-1)[0].cpu().numpy()
    return {label_names[i]: float(probs[i]) for i in range(len(label_names))}

# Launch Gradio interface
demo = gr.Interface(
    fn=classify_news,
    inputs=gr.Textbox(
        lines=3,
        placeholder="Enter a news headline here...",
        label="News Headline"
    ),
    outputs=gr.Label(num_top_classes=4, label="Topic Probabilities"),
    title="📰 News Topic Classifier (BERT)",
    description="Fine-tuned BERT model classifying news into: World | Sports | Business | Sci/Tech",
    examples=[
        ["NASA launches new telescope to study distant galaxies"],
        ["Stock market hits record high amid strong earnings"],
        ["Brazil wins the World Cup in a thrilling final"],
        ["UN security council meets to discuss ceasefire in conflict zone"]
    ],
    theme=gr.themes.Soft()
)

demo.launch(share=True)  # share=True gives a public URL in Colab

