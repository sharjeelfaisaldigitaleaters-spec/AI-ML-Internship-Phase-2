import numpy as np
import pandas as pd
import torch
import matplotlib.pyplot as plt
import seaborn as sns
from datasets import load_dataset
from transformers import (
    BertTokenizer,
    BertForSequenceClassification,
    TrainingArguments,
    Trainer,
    DataCollatorWithPadding
)
from sklearn.metrics import accuracy_score, f1_score, classification_report, confusion_matrix
import warnings
warnings.filterwarnings("ignore")

# Check GPU availability
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print(f"Using device: {device}")

# Load AG News dataset - using full namespace path to fix HfUriError
print("Loading AG News dataset...")

# Fix: use "fancyzhx/ag_news" instead of "ag_news"
dataset = load_dataset("fancyzhx/ag_news")

print(f"\nDataset structure:\n{dataset}")
print(f"\nTrain samples: {len(dataset['train'])}")
print(f"Test samples:  {len(dataset['test'])}")

# Label mapping
label_names = dataset['train'].features['label'].names
print(f"\nClasses: {label_names}")
# 0: World, 1: Sports, 2: Business, 3: Sci/Tech

# Preview a few samples
print("\n--- Sample Records ---")
for i in range(3):
    print(f"Text: {dataset['train'][i]['text'][:100]}...")
    print(f"Label: {label_names[dataset['train'][i]['label']]}\n")

# Class distribution
train_labels = dataset['train']['label']
label_counts = pd.Series(train_labels).value_counts().sort_index()

plt.figure(figsize=(8, 5))
bars = plt.bar([label_names[i] for i in label_counts.index], label_counts.values,
               color=['#2196F3', '#4CAF50', '#FF9800', '#E91E63'])
plt.title('AG News – Class Distribution (Training Set)', fontsize=14, fontweight='bold')
plt.xlabel('Category')
plt.ylabel('Number of Samples')
for bar, val in zip(bars, label_counts.values):
    plt.text(bar.get_x() + bar.get_width()/2, bar.get_height() + 200,
             f'{val:,}', ha='center', fontweight='bold')
plt.tight_layout()
plt.savefig('class_distribution.png', dpi=150)
plt.show()
print("Class distribution is balanced ✓")

# Using a subset for faster training on Colab (remove/increase for full training)
TRAIN_SIZE = 8000   # out of 120,000
TEST_SIZE  = 2000   # out of 7,600

train_subset = dataset['train'].shuffle(seed=42).select(range(TRAIN_SIZE))
test_subset  = dataset['test'].shuffle(seed=42).select(range(TEST_SIZE))

print(f"Using {TRAIN_SIZE} training samples and {TEST_SIZE} test samples")
print("(Increase TRAIN_SIZE for better accuracy — full dataset has 120k train samples)")

# Load BERT tokenizer
MODEL_NAME = "bert-base-uncased"
tokenizer = BertTokenizer.from_pretrained(MODEL_NAME)

def tokenize_function(examples):
    return tokenizer(
        examples["text"],
        padding=False,        # handled by DataCollator
        truncation=True,
        max_length=128
    )

# Apply tokenization
print("Tokenizing dataset...")
tokenized_train = train_subset.map(tokenize_function, batched=True, remove_columns=["text"])
tokenized_test  = test_subset.map(tokenize_function, batched=True, remove_columns=["text"])

# Rename label column to 'labels' as expected by HuggingFace Trainer
tokenized_train = tokenized_train.rename_column("label", "labels")
tokenized_test  = tokenized_test.rename_column("label", "labels")

# ✅ Fix: Do NOT use set_format("torch") — causes torchvision VideoReader bug
# The Trainer handles tensor conversion internally
tokenized_train = tokenized_train.with_format("numpy")
tokenized_test  = tokenized_test.with_format("numpy")

print("Tokenization complete ✓")
print(f"Sample token ids: {tokenized_train[0]['input_ids'][:10]}")
print(f"Columns: {tokenized_train.column_names}")

# Load BERT for sequence classification (4 classes)
num_labels = len(label_names)

model = BertForSequenceClassification.from_pretrained(
    MODEL_NAME,
    num_labels=num_labels,
    id2label={i: name for i, name in enumerate(label_names)},
    label2id={name: i for i, name in enumerate(label_names)}
)

model = model.to(device)
print(f"Model loaded: {MODEL_NAME}")
print(f"Number of parameters: {sum(p.numel() for p in model.parameters()):,}")
print(f"Trainable parameters: {sum(p.numel() for p in model.parameters() if p.requires_grad):,}")

# Data collator for dynamic padding
data_collator = DataCollatorWithPadding(tokenizer=tokenizer)

# Metrics function used during evaluation
def compute_metrics(eval_pred):
    logits, labels = eval_pred
    predictions = np.argmax(logits, axis=-1)
    acc = accuracy_score(labels, predictions)
    f1  = f1_score(labels, predictions, average='weighted')
    return {
        "accuracy": acc,
        "f1_weighted": f1
    }

training_args = TrainingArguments(
    output_dir="./bert-ag-news",
    num_train_epochs=3,
    per_device_train_batch_size=16,
    per_device_eval_batch_size=32,
    warmup_steps=100,
    weight_decay=0.01,
    learning_rate=2e-5,
    eval_strategy="epoch",        # ✅ Fixed: was 'evaluation_strategy'
    save_strategy="epoch",
    load_best_model_at_end=True,
    metric_for_best_model="f1_weighted",
    logging_dir="./logs",
    logging_steps=50,
    report_to="none",
    fp16=torch.cuda.is_available()
)

print("Training arguments configured ✓")

trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=tokenized_train,
    eval_dataset=tokenized_test,
    processing_class=tokenizer,   # ✅ Fixed: was 'tokenizer'
    data_collator=data_collator,
    compute_metrics=compute_metrics
)

print("Starting training...")
print("="*60)
train_result = trainer.train()

print("\n✅ Training Complete!")
print(f"Training Loss: {train_result.training_loss:.4f}")

print("Evaluating on test set...")
results = trainer.evaluate()

print("\n📊 Evaluation Results:")
print(f"  Accuracy  : {results['eval_accuracy']*100:.2f}%")
print(f"  F1 Score  : {results['eval_f1_weighted']:.4f}")
print(f"  Eval Loss : {results['eval_loss']:.4f}")

"""Detailed Classification Report + Confusion Matrix"""

# Get predictions for the full test set
predictions_output = trainer.predict(tokenized_test)
preds = np.argmax(predictions_output.predictions, axis=-1)
true_labels = predictions_output.label_ids

# Classification Report
print("=" * 60)
print("CLASSIFICATION REPORT")
print("=" * 60)
print(classification_report(true_labels, preds, target_names=label_names))

# Confusion Matrix
cm = confusion_matrix(true_labels, preds)
plt.figure(figsize=(8, 6))
sns.heatmap(cm, annot=True, fmt='d', cmap='Blues',
            xticklabels=label_names, yticklabels=label_names,
            linewidths=0.5)
plt.title('Confusion Matrix – BERT on AG News', fontsize=14, fontweight='bold')
plt.ylabel('True Label')
plt.xlabel('Predicted Label')
plt.tight_layout()
plt.savefig('confusion_matrix.png', dpi=150)
plt.show()

"""Training Loss Curve"""

# Plot training loss over steps from trainer logs
log_history = trainer.state.log_history
train_losses = [(x['step'], x['loss']) for x in log_history if 'loss' in x and 'eval_loss' not in x]
eval_losses  = [(x['step'], x['eval_loss']) for x in log_history if 'eval_loss' in x]

steps_t, losses_t = zip(*train_losses)
steps_e, losses_e = zip(*eval_losses)

plt.figure(figsize=(10, 4))
plt.plot(steps_t, losses_t, label='Train Loss', color='#2196F3', linewidth=2)
plt.scatter(steps_e, losses_e, label='Eval Loss', color='#E91E63', s=80, zorder=5)
plt.xlabel('Steps')
plt.ylabel('Loss')
plt.title('Training & Evaluation Loss', fontsize=13, fontweight='bold')
plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.savefig('loss_curve.png', dpi=150)
plt.show()

"""Save the Model"""

# Save model and tokenizer
model.save_pretrained("./bert-ag-news-final")
tokenizer.save_pretrained("./bert-ag-news-final")
print("✅ Model saved to './bert-ag-news-final'")

